from typing import Literal
from urllib.parse import urlparse

from pydantic import BaseModel, Field, field_validator

KnowledgeUseCase = Literal[
    "market_research",
    "company_diligence",
    "supply_chain",
    "risk_assessment",
    "scenario_analysis",
    "leadership",
    "macro_context",
]
DocumentType = Literal[
    "annual_report",
    "regulatory_filing",
    "earnings_transcript",
    "company_presentation",
    "supplier_disclosure",
    "news",
    "policy",
    "research_note",
    "other",
]
SourceTrust = Literal["primary", "institutional", "issuer", "discovery", "provided_dataset", "unknown"]


class KnowledgeSearchRequest(BaseModel):
    query: str = Field(min_length=3, max_length=1200)
    persona: Literal["amira", "mateo", "robert"] = "mateo"
    use_case: KnowledgeUseCase
    entity_id: str | None = Field(default=None, max_length=64)
    document_type: DocumentType | None = None
    published_after: str | None = Field(default=None, max_length=35)
    limit: int = Field(default=6, ge=1, le=12)

    @field_validator("entity_id")
    @classmethod
    def validate_entity_id(cls, value: str | None) -> str | None:
        if value is not None and not value.replace("-", "").replace(".", "").isalnum():
            raise ValueError("entity_id must contain only letters, digits, dots, or hyphens")
        return value.upper() if value else None


class KnowledgeUploadRequest(BaseModel):
    persona: Literal["amira", "mateo", "robert"] = "mateo"
    filename: str = Field(min_length=1, max_length=180)
    title: str = Field(min_length=1, max_length=240)
    source_url: str = Field(min_length=8, max_length=2000)
    source_id: str = Field(min_length=2, max_length=80)
    source_trust: SourceTrust
    use_case: KnowledgeUseCase
    document_type: DocumentType
    entity_id: str | None = Field(default=None, max_length=64)
    published_at: str | None = Field(default=None, max_length=35)
    license_status: Literal["permitted", "restricted", "unknown"] = "unknown"

    @field_validator("filename")
    @classmethod
    def validate_filename(cls, value: str) -> str:
        name = value.rsplit("/", 1)[-1].rsplit("\\", 1)[-1]
        if name != value or "." not in name:
            raise ValueError("filename must be a basename with an extension")
        if name.lower().endswith(".metadata.json"):
            raise ValueError("metadata sidecar files are generated by the server")
        if name.rsplit(".", 1)[-1].lower() not in {"pdf", "txt", "md", "html", "htm", "csv", "doc", "docx", "xls", "xlsx"}:
            raise ValueError("unsupported document type")
        return name

    @field_validator("entity_id")
    @classmethod
    def validate_entity_id(cls, value: str | None) -> str | None:
        if value is not None and not value.replace("-", "").replace(".", "").isalnum():
            raise ValueError("entity_id must contain only letters, digits, dots, or hyphens")
        return value.upper() if value else None

    @field_validator("source_url")
    @classmethod
    def validate_source_url(cls, value: str) -> str:
        parsed = urlparse(value)
        if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError("source_url must be a public HTTPS URL")
        return value
