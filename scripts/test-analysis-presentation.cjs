const { chromium } = require(require.resolve('@playwright/test', { paths: [require('node:path').join(__dirname, '../apps/web')] }));
const assert = require('node:assert/strict');
const { capture } = require('./browser-capture.cjs');
const base = process.env.INVESTOROS_TEST_URL || 'http://127.0.0.1:5175';
const analysisId = process.env.INVESTOROS_TEST_ANALYSIS_ID;
if (!analysisId) throw new Error('Set INVESTOROS_TEST_ANALYSIS_ID to a completed NVDA analysis for Mateo.');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1757, height: 1183 } });
    const errors = []; const newsRequests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.url().includes('/simulation/news/')) newsRequests.push(request.url()); });
    await page.goto(`${base}/app/assistant?analysis_id=${encodeURIComponent(analysisId)}`);
    await page.getByRole('heading', { name: 'NVDA · explorer l’analyse' }).waitFor({ timeout: 60000 });
    await page.locator('.hx-chart .recharts-line-curve').first().waitFor();
    assert(await page.locator('.hx-chart .recharts-area-area').count() >= 2, 'Forecast band is missing');
    assert(newsRequests.length > 0, 'News was not requested');
    const marker = page.locator('.hx-rich-marker').first();
    await marker.hover();
    await page.getByRole('region', { name: 'Aperçu des événements' }).waitFor();
    const preview = page.locator('.hx-event-preview');
    assert.match(await preview.innerText(), /2026/);
    await preview.hover();
    const hoverShot = await capture(page, 'investoros-market-hover');
    await preview.locator('button').first().click();
    await page.locator('.aj-dialog[open]').waitFor();
    assert(await page.getByRole('link', { name: 'Lire la source', exact: false }).count());
    await page.getByRole('button', { name: 'Fermer la fiche', exact: true }).click();
    await marker.focus(); await page.keyboard.press('Enter');
    await page.locator('.aj-dialog[open]').waitFor();
    await page.getByRole('button', { name: 'Fermer la fiche', exact: true }).click();
    const forecast = page.getByRole('button', { name: 'Estimation p10–p90', exact: true });
    await forecast.click(); assert.equal(await page.locator('.hx-chart .recharts-line-curve').count(), 0);
    await forecast.click(); await page.locator('.hx-chart .recharts-line-curve').first().waitFor();
    await page.getByRole('button', { name: '1M', exact: true }).click();
    await page.getByRole('button', { name: '3M', exact: true }).click();
    await page.getByRole('button', { name: /^Consulter les sources ·/ }).click();
    await page.locator('.source-details-dialog[open]').waitFor();
    assert(await page.locator('.source-details-dialog[open] article').count() > 0);
    assert.match(await page.locator('.source-details-dialog[open]').innerText(), /Consultée/);
    const sourceShot = await capture(page, 'investoros-market-sources');
    await page.getByRole('button', { name: 'Fermer les sources', exact: true }).click();
    const metric = page.locator('.rr-metrics dd').first();
    const quarter = await metric.innerText();
    await page.getByRole('button', { name: 'Dernier exercice', exact: true }).click();
    assert.notEqual(await metric.innerText(), quarter);
    await page.getByRole('button', { name: 'Dernier trimestre', exact: true }).click();
    await page.locator('.rr-exact>summary').click();
    assert.match(await page.locator('.rr-exact table').innerText(), /USD/);
    await page.locator('.rr-exact>summary').click();
    await page.locator('.rr-section').first().scrollIntoViewIfNeeded();
    const reportShot = await capture(page, 'investoros-market-report');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${base}/app/analyses?analysis_id=${encodeURIComponent(analysisId)}`);
    await page.locator('.hx-rich-marker').first().waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false, 'Mobile horizontal overflow');
    const mobileShot = await capture(page, 'investoros-market-mobile');
    // Controlled fixtures exercise optional images and their fallback, not the live news claim.
    await page.route('**/v1/simulation/news/NVDA', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ ticker: 'NVDA', available: true, source: 'Test fixture', articles: [{ id: 'image-test', title: 'Image fournie — test', url: 'https://example.org/test-only', domain: 'example.org', indexedAt: '2026-11-10T14:00:00Z', imageUrl: `${base}/test-only-event.png` }] }) }));
    await page.route('**/test-only-event.png', route => route.fulfill({ contentType: 'image/png', body: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jN1kAAAAASUVORK5CYII=', 'base64') }));
    await page.reload();
    await page.locator('.hx-news-grid img').first().waitFor();
    assert(await page.locator('.hx-news-grid img').first().evaluate(image => image.complete && image.naturalWidth > 0));
    await page.getByRole('button', { name: 'Actualiser les actualités', exact: true }).click();
    await page.unroute('**/test-only-event.png');
    await page.route('**/test-only-event.png', route => route.fulfill({ status: 404, body: 'missing' }));
    await page.reload();
    await page.getByRole('button', { name: /Image fournie — test/ }).waitFor();
    await page.waitForFunction(() => !document.querySelector('.hx-news-grid img'));
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({ result: 'passed', forecastCurveAndBand: true, eventHoverAndKeyboard: true, sourcesAndDates: true, financialPeriods: true, imagesAndFallback: true, mobile: true, errors, captures: [hoverShot, sourceShot, reportShot, mobileShot] }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
