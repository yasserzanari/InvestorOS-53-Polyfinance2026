const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright-core');
const { PNG } = require('pngjs');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5175';
const api = process.env.TEST_API_URL || 'http://127.0.0.1:8010';
const id = process.env.TEST_ANALYSIS_ID || '871ca17e-cd15-4f85-ba45-5bc2bc0f6fd1';

(async () => {
  const response = await fetch(`${api}/v1/profiles/research/${id}?accountId=mateo`);
  assert(response.ok, 'Use an existing, accessible analysis; this test never starts a new one');
  const run = await response.json();
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1565, height: 1183 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/app/analyses?analysis_id=${id}`);
    const dossier = page.getByRole('region', { name: 'Dossier d’analyse' });
    await dossier.waitFor({ timeout: 45000 });
    await page.locator('.hx-chart').first().waitFor();
    const sidebar = page.locator('.ad-sidebar');
    assert.equal(await sidebar.locator('.ra-source-list button').count(), run.evidence.length);
    await sidebar.getByRole('button', { name: /SEC · États financiers/ }).click();
    await sidebar.getByRole('button', { name: 'Données reçues', exact: true }).click();
    assert((await sidebar.locator('.ra-json').innerText()).includes('annual_financials'));
    const sourceHref = await sidebar.getByRole('link', { name: 'Ouvrir le site de la source' }).getAttribute('href');
    assert(sourceHref.startsWith('https://data.sec.gov/'));
    await sidebar.getByRole('button', { name: /^Journal/ }).click();
    assert.equal(await sidebar.locator('.ra-journal article').count(), run.events.length);
    const nav = page.getByRole('navigation', { name: 'Explorer les résultats' });
    await nav.getByRole('button', { name: 'Activité', exact: true }).click();
    await page.locator('.ra-canvas .react-flow__node').first().waitFor();
    const nodeCount = await page.locator('.ra-canvas .react-flow__node').count();
    assert(nodeCount > 1);
    await page.locator('.ra-canvas .react-flow__node').filter({ hasText: 'Planificateur' }).click();
    const canvasJournal = page.locator('.ad-main .ra-journal');
    assert.equal(await canvasJournal.locator('article').count(), run.events.filter(event => event.agent_id === 'coordinator').length);
    await nav.getByRole('button', { name: 'Événements', exact: true }).click();
    await page.locator('.aj-events>button').first().click();
    await page.getByRole('dialog').waitFor();
    assert(await page.getByRole('dialog').getByRole('link', { name: /Lire la source/ }).count());
    await page.getByRole('button', { name: 'Fermer la fiche', exact: true }).click();
    await nav.getByRole('button', { name: 'Carte', exact: true }).click();
    await page.locator('.av-world-map').waitFor();
    await nav.getByRole('button', { name: 'Dépendances', exact: true }).click();
    await page.locator('.av-graph-node').first().waitFor();
    await nav.getByRole('button', { name: 'Entreprise', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Mobile page must not overflow horizontally');
    await page.setViewportSize({ width: 1565, height: 1183 });
    await page.locator('.workspace-content').evaluate(el => { el.scrollTop = 0; });
    const capture = `${process.env.HOME}/.cache/analysis-dossier-verified-${Date.now()}.png`;
    await page.screenshot({ path: capture + '.tmp', type: 'png', fullPage: true });
    PNG.sync.read(fs.readFileSync(capture + '.tmp'), { checkCRC: true });
    fs.renameSync(capture + '.tmp', capture);

    let requests = 0;
    await page.route('**/v1/profiles/research/*', route => {
      requests++;
      const partial = requests < 3;
      return route.fulfill({ json: partial ? { ...run, status: 'running', result: undefined, completed_at: undefined, evidence: requests === 1 ? [] : run.evidence.slice(0, 2), events: run.events.slice(0, requests === 1 ? 5 : 10) } : run });
    });
    await page.reload();
    await page.getByText('Recherche en cours', { exact: true }).waitFor();
    await page.locator('.ad-main .ra-canvas').waitFor();
    assert.equal(await page.locator('.ad-sidebar .ra-source-list button').count(), 0);
    await page.waitForFunction(() => document.querySelectorAll('.ad-sidebar .ra-source-list button').length === 2, { timeout: 12000 });
    await page.getByText('Analyse terminée', { exact: true }).waitFor({ timeout: 12000 });
    assert.equal(await page.locator('.ad-sidebar .ra-source-list button').count(), run.evidence.length);
    await page.unroute('**/v1/profiles/research/*');
    await page.route('**/v1/profiles/research/*', route => route.fulfill({ status: 503, json: { detail: 'Indisponibilité de contrôle' } }));
    await page.getByRole('button', { name: 'Actualiser l’analyse', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: '503' }).waitFor();
    assert.equal(await page.locator('.ad-sidebar .ra-source-list button').count(), run.evidence.length, 'A refresh failure must preserve the received sources');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, actualSources: run.evidence.length, recordedAgents: nodeCount, interactions: ['source data', 'external source link', 'event details', 'agent canvas selection', 'map', 'dependencies', 'mobile', 'partial results while polling'], capture }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
