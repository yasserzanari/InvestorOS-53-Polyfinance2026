const { chromium } = require(require.resolve('@playwright/test', { paths: [require('node:path').join(__dirname, '../apps/web')] }));
const assert = require('node:assert/strict');
const { capture } = require('./browser-capture.cjs');
const base = process.env.INVESTOROS_TEST_URL || 'http://127.0.0.1:5175';
const analysisId = process.env.INVESTOROS_TEST_ANALYSIS_ID;
if (!analysisId) throw new Error('Set INVESTOROS_TEST_ANALYSIS_ID to a completed NVDA analysis for Mateo.');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'], ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1757, height: 1183 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const url = `${base}/app/assistant?analysis_id=${encodeURIComponent(analysisId)}`;
    await page.goto(url);
    await page.getByRole('button', { name: 'Dépendances', exact: true }).waitFor({ timeout: 60000 });
    assert.equal(await page.getByText('Résultats du moteur de recherche AWS', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('heading', { name: 'Résultats de recherche', exact: true }).isVisible(), false);
    assert.equal(await page.getByRole('button', { name: 'Actualiser le suivi', exact: true }).count(), 1);
    const width = await page.locator('.pw-research-results').evaluate(element => ({ actual: element.getBoundingClientRect().width, parent: element.parentElement.clientWidth }));
    assert(width.actual / width.parent > .94, `Content restricted to ${width.actual}/${width.parent}`);
    await page.getByRole('button', { name: 'Dépendances', exact: true }).click();
    await page.locator('.nd-node').first().waitFor();
    assert.equal(await page.locator('.nd-node').count(), 8);
    await page.waitForFunction(() => [...document.querySelectorAll('.nd-node')].every(element => element.getBoundingClientRect().width > 190));
    const canvas = page.locator('.nd-network .av-network-canvas');
    const before = await canvas.boundingBox();
    assert(before.width > width.actual * .97, 'Graph leaves unused horizontal space');
    assert.equal(await page.locator('.nd-inspector').count(), 0);
    const separator=page.getByRole('separator',{name:'Redimensionner le chat et les onglets',exact:true});
    await separator.focus();await page.keyboard.press('Home');
    await page.waitForFunction(()=>document.querySelector('.pw-research-results').clientWidth>1000);
    const wide=await page.locator('.pw-research-results').evaluate(element=>element.clientWidth/element.parentElement.clientWidth);assert(wide>.95,'Result remains capped on a wide panel');
    await separator.focus();for(let i=0;i<12;i++)await page.keyboard.press('ArrowRight');
    await page.waitForTimeout(180);
    const stableBefore=await canvas.boundingBox();
    const graphShot = await capture(page, 'investoros-network-readable');
    await page.locator('.react-flow__node[data-id="tsmc"]').click();
    await page.locator('.nd-inspector').waitFor();
    const after = await canvas.boundingBox();
    assert(after.width / stableBefore.width > .98, `Inspector changed width: ${stableBefore.width} -> ${after.width}`);
    assert.equal(await page.locator('.nd-inspector').evaluate(element => getComputedStyle(element).position), 'absolute');
    assert.match(await page.locator('.nd-inspector').innerText(), /TSMC/);
    assert.equal(await page.locator('.aj-dialog[open]').count(), 0, 'Selection unexpectedly opened a modal');
    await page.getByRole('button', { name: 'Explorer cet élément', exact: true }).click();
    await page.locator('.aj-dialog[open]').waitFor();
    assert((await page.getByRole('link', { name: 'Lire la source', exact: false }).getAttribute('href')).startsWith('https://'));
    await page.getByRole('button', { name: 'Fermer la fiche', exact: true }).click();
    const inspectorShot = await capture(page, 'investoros-network-inspector');
    await page.getByRole('button', { name: 'Fermer les détails du réseau', exact: true }).click();
    await page.getByRole('button',{name:'Lire les sources de TSMC',exact:true}).click();await page.locator('.aj-dialog[open]').waitFor();assert(!((await page.locator('.aj-dialog[open]').innerText()).includes('1 janvier 2026')));await page.getByRole('button',{name:'Fermer la fiche',exact:true}).click();
    await page.getByRole('combobox', { name: 'Afficher', exact: true }).selectOption('supplier');
    await page.waitForFunction(() => document.querySelectorAll('.nd-node').length === 7);
    await page.getByRole('combobox', { name: 'Afficher', exact: true }).selectOption('all');
    await page.waitForFunction(() => document.querySelectorAll('.nd-node').length === 8);
    await page.getByRole('combobox', { name: 'Risque', exact: true }).selectOption('high');
    await page.getByText('Aucun élément ne correspond aux filtres sélectionnés.', { exact: true }).waitFor();
    await page.getByRole('combobox', { name: 'Risque', exact: true }).selectOption('all');
    await page.waitForFunction(() => document.querySelectorAll('.nd-node').length === 8);
    await page.locator('.react-flow__node[data-id="tsmc"]').focus();
    await page.keyboard.press('Enter'); await page.locator('.nd-inspector').waitFor();
    await page.getByRole('button', { name: 'Fermer les détails du réseau', exact: true }).click();
    await page.locator('.nd-role-bars').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('.nd-role-bars>button').count(), 3);
    const counts = await page.locator('.nd-role-bars>button>em').allTextContents();
    assert.deepEqual(counts, ['2', '3', '3']);
    assert.match(await page.locator('.nd-role-bars').innerText(), /ne sont pas des parts/);
    await page.locator('.av-network-watchlist').scrollIntoViewIfNeeded();
    assert.equal(await page.locator('.av-network-watchlist tbody tr').count(), 8);
    const tableWidth = await page.locator('.av-network-watchlist table').boundingBox();
    const tableParent = await page.locator('.av-network-watchlist-scroll').boundingBox();
    assert(tableWidth.width / tableParent.width > .98);
    const barsShot = await capture(page, 'investoros-network-data-bars');
    await page.locator('.nd-role-bars>button').first().click();await page.waitForFunction(()=>document.querySelectorAll('.nd-node').length===3);await page.getByRole('button',{name:'Fondeur',exact:true}).click();await page.waitForFunction(()=>document.querySelectorAll('.nd-node').length===8);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(url);
    await page.getByRole('button', { name: 'Dépendances', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Dépendances', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.nd-node')].every(element => element.getBoundingClientRect().width >= 190));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 2), false, 'Mobile overflow');
    const mobileShot = await capture(page, 'investoros-network-mobile');
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({ result: 'passed', fullWidth: true, readableNodes: true, floatingInspector: true, sourceLinks: true, filtersAndKeyboard: true, documentedFunctionCounts: counts, tableWidth: true, mobile: true, errors, captures: [graphShot, inspectorShot, barsShot, mobileShot] }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
